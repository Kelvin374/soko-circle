-- =====================================================================
-- 6. documented_notes -> gap_reports (one deep-dive per county that has notes)
--    tag/icon/title are derived from the county's archetype.
-- =====================================================================
insert into public.gap_reports (
  slug, category, location, tag, icon, title, description, report_type, is_unlocked, county_code
)
select
  'county-gap-report-' || ga.county_code,
  'County Gap Signal',
  ga.location,
  ar.label,
  case ga.archetype
    when 'A_metro_port_hub' then 'building-storefront'
    when 'B_upper_middle_commercial' then 'chart-bar'
    when 'C_large_mass_market' then 'squares-2x2'
    when 'D_mid_size_lower_middle' then 'map'
    when 'E_very_low_income' then 'map-pin'
    when 'F_high_growth_frontier' then 'rocket-launch'
    else 'chart-bar'
  end,
  ga.location || ': ' || ar.label,
  ga.documented_notes,
  'demographics',
  false,
  ga.county_code
from public.gap_analytics ga
join public.gap_archetypes ar on ar.code = ga.archetype
where ga.county_code is not null
  and ga.documented_notes is not null
on conflict (slug) do update set
  category = excluded.category,
  location = excluded.location,
  tag = excluded.tag,
  icon = excluded.icon,
  title = excluded.title,
  description = excluded.description,
  report_type = excluded.report_type,
  is_unlocked = excluded.is_unlocked,
  county_code = excluded.county_code;
