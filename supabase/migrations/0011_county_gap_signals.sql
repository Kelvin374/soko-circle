-- =====================================================================
-- 2. Geo reference tables (real data) + categorisation columns
--    subcounties   290  IEBC/administrative level 2, conterminous with
--                       constituencies (subcounty_code == constituency code)
--    constituencies 290  IEBC
--    wards         1450  IEBC
--    towns          307  KNBS 2019 census urban centres (with population)
--    Codes = source ids minus the "KE" prefix; county_code matches 001-047.
-- =====================================================================
create table if not exists public.subcounties (
  code text primary key,
  county_code text not null references public.counties(code),
  name text not null,
  latitude numeric, longitude numeric
);
create table if not exists public.constituencies (
  code text primary key,
  county_code text not null references public.counties(code),
  subcounty_code text references public.subcounties(code),
  name text not null
);
create table if not exists public.wards (
  code text primary key,
  constituency_code text not null references public.constituencies(code),
  name text not null,
  latitude numeric, longitude numeric
);
create table if not exists public.towns (
  code text primary key,
  county_code text references public.counties(code),
  name text not null,
  population_2019 int,
  county_label text
);
create index if not exists subcounties_county_idx on public.subcounties (county_code);
create index if not exists constituencies_county_idx on public.constituencies (county_code);
create index if not exists wards_constituency_idx on public.wards (constituency_code);
create index if not exists towns_county_idx on public.towns (county_code);

alter table public.subcounties enable row level security;
alter table public.constituencies enable row level security;
alter table public.wards enable row level security;
alter table public.towns enable row level security;
do $$ declare t text; begin
  foreach t in array array['subcounties','constituencies','wards','towns'] loop
    if not exists (select 1 from pg_policies where schemaname='public' and tablename=t and policyname='Public read '||t) then
      execute format('create policy %I on public.%I for select using (true)', 'Public read '||t, t);
    end if;
  end loop;
end $$;

