--
-- REWRITE NOTE
--  This replaces the standalone `county_gap_signals` table with the three tables
--  the app actually reads on the Gap Map, mapped by how each field is used:
--
--    gap_archetypes  <- the 6 rule-based archetypes (reference/lookup).
--    gap_analytics   <- EXTENDED with the real county signal columns; one row per
--                       county (slug = 'county-gap-<code>'). This is the table the
--                       "Opportunity Score" card reads (fetchAnalytics).
--    gap_reports     <- one deep-dive card per county that has documented_notes
--                       (slug = 'county-gap-report-<code>'), titled "<County>: <archetype>".
--                       This is the table the "Deep-Dive Gap Reports" list reads.
--
--  County rows use the sentinel category 'County Gap Signal' because the signals
--  are county-wide, not sector-specific. The selection screen currently calls
--  fetchAnalytics(<category>, <location>) with a real category, so to surface these
--  rows the app must query category = 'County Gap Signal' (or omit the category
--  filter) alongside its normal sector lookup.
--
-- GEO CATEGORISATION (real data)
--  Reference tables let a gap be categorised below county level:
--    subcounties    290  IEBC/administrative level 2 (conterminous with
--                        constituencies -> subcounty_code == constituency code)
--    constituencies 290  IEBC
--    wards         1450  IEBC
--    towns          307  KNBS 2019 census urban centres (with population)
--  Codes are source ids with the "KE" prefix stripped; county_code matches
--  public.counties.code (001-047). gap_analytics / gap_reports gain nullable
--  subcounty_code / constituency_code / ward_code / town_code columns.
--  Sources: IEBC boundaries via open-admin-data (CC-BY-4.0); KNBS 2019 census
--  Volume II (Table 2.5, urban centres).
--
-- WHAT THIS IS / ISN'T
--  * Numeric columns are real: KNBS Gross County Product (2020-24, via Wikipedia
--    table), FinAccess 2024, KNBS/KIPPRA MSME 2016, official CAIP statements.
--  * `archetype` is a RULE-BASED tag computed from those numbers (rules stored in
--    gap_archetypes). It is NOT an official statistic.
--  * No public dataset gives sector-level supply counts per county, so this does
--    NOT say "county X lacks product Y". Use it to prioritise where to look.
--  * Show the year and source next to every figure in the UI.
-- =====================================================================

-- The consolidated data no longer lives in a dedicated table.
